// Builds src/protected-words.ts: the real English words (Webster's Second, public domain, /usr/share/dict/words
// on macOS and most Unix systems) that the offline spelling fixer could otherwise "correct" into a common word.
// Run after changing src/words.ts:  pnpm --filter @promptforge/core build && node scripts/protected-words.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { isKnownWord, nearestWord } from '../dist/spell.js';

const dict = readFileSync(process.argv[2] ?? '/usr/share/dict/words', 'utf8').split('\n').filter((w) => /^[a-z]{4,}$/.test(w));
const keep = [];
let done = 0;
for (const w of dict) {
  if (++done % 20000 === 0) process.stderr.write(`${done}/${dict.length}\r`);
  if (!isKnownWord(w) && nearestWord(w)) keep.push(w);
}
writeFileSync(
  new URL('../src/protected-words.ts', import.meta.url),
  `// Generated by scripts/protected-words.mjs. Do not edit by hand.\n// ${keep.length} real words close to a common word, from Webster's Second International (public domain).\nexport const PROTECTED_WORDS =\n  '${keep.join(' ')}';\n`,
);
console.log(`\n${keep.length} protected words of ${dict.length}`);
